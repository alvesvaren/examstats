import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { parseAnswerChart, parseReport, parseSearchForm, parseSurveyRows, parseTitle } from "./evaluation-pages.ts";

/** One chart and its mean and median table, as the report page renders every scale question. */
const meanTable = (question: string, mean: string, { header = "Medelv&#228;rde", chart = "chart" } = {}) =>
  `<div class="srchartWrapper"><img class="srchart" alt="" src="images/loading.gif?k=${chart}" /></div></div></div><div class="artBaseRow"><div class="artWrapper"><table class="srtbl" cellpadding="2" cellspacing="0" summary=""><thead><tr class="srtbl-h1"><td class="srtbl-t1">&nbsp;</td><th class="srtbl-t1">${header}</th><th class="srtbl-t1">Median</th></tr></thead><tbody><tr class="srtbl-row"><th class="srtbl-rh">${question}</th><td class="srtbl-cell">${mean}</td><td class="srtbl-cell">4,00</td></tr></tbody></table>`;

describe("parseReport", () => {
  it("reads counts, minutes and the standard questions of a Swedish report", () => {
    const html = [
      `<div class="srTextWrapper"><h1 style="text-align: center;">TMA970 Inledande matematisk analys 2024/2025 LP1-LP1</h1><hr /><hr /><p style="text-align: center;">Antal respondenter: 230<br />Antal svar: 74<br />Svarsfrekvens: 32,17 %<br /></p><hr /></div>`,
      `<p style="text-align: center;" data-autogenerated="protocol-link"><a href="https://webbpublicering360.portal.chalmers.se/Extern/Home/Download?recordnor=1018625%262024_12&amp;st" target="_blank">Länk till protokoll</a></p>`,
      meanTable("Jag hade tillräckliga förkunskaper för att kunna följa kursen", "4,15"),
      meanTable(
        `Lärandemålen (se <a href="https://example.com" target="_blank">kursplanen</a>) beskriver tydligt vad jag förväntades lära mig`,
        "3,9",
      ),
      meanTable("Kursens struktur (uppdelningen i föreläsningar, övningar, laborationer, simuleringar etc.) är lämplig", "3,92"),
      meanTable("Kursens struktur, undervisning och examination var utformad så att jag upplever att jag har kunnat lära mig", "4,66"),
      meanTable("Kursens arbetsbelastning i förhållande till antalet poäng var...", "3,72"),
      meanTable("Hur nöjd är du med gästföreläsningarna?", "2,10"),
      meanTable("Vad är ditt sammanfattande intryck av kursen?", "3,53", { chart: "overall" }),
    ].join("\n");

    expect(parseReport(html)).toEqual({
      respondents: 230,
      answers: 74,
      minutes: "https://webbpublicering360.portal.chalmers.se/Extern/Home/Download?recordnor=1018625%262024_12&st",
      means: { prerequisites: 4.15, learningOutcomes: 3.9, structure: 3.92, workload: 3.72, overall: 3.53 },
      overallChart: "?k=overall",
    });
  });

  it("reads an English report without minutes", () => {
    const html = [
      `<h1 style="text-align: center;">DAT246 Empirical software engineering 2021/2022 LP1-LP1</h1><hr /><hr /><p style="text-align: center;">Respondents: 98<br />Answer Count: 30<br />Answer Frequency: 30.61%<br /></p>`,
      meanTable("The teaching worked well", "4.00", { header: "Mean" }),
      meanTable("What is your overall impression of the course?", "3.804", { header: "Mean", chart: "overall" }),
    ].join("\n");

    expect(parseReport(html)).toEqual({
      respondents: 98,
      answers: 30,
      minutes: null,
      means: { teaching: 4, overall: 3.8 },
      overallChart: "?k=overall",
    });
  });

  it("fails on a page without answer counts, such as the site's error page", () => {
    expect(() => parseReport("<title>Survey&amp;Report - Error</title>")).toThrow("no answer counts");
  });
});

describe("parseAnswerChart", () => {
  // The overall question of DAT265 2019/20: 0, 1, 8, 14 and 6 answers, mean 3.86.
  const chart = readFileSync(new URL("fixtures/overall-chart.png", import.meta.url));

  it("reads answers per option from the bar lengths", () => {
    expect(parseAnswerChart(chart, 29, 3.86)).toEqual([0, 1, 8, 14, 6]);
  });

  it("allows respondents who skipped the question", () => {
    expect(parseAnswerChart(chart, 33, 3.86)).toEqual([0, 1, 8, 14, 6]);
  });

  it("gives null when no count matches the reported mean", () => {
    expect(parseAnswerChart(chart, 29, 3.5)).toBeNull();
  });
});

describe("parseTitle", () => {
  it.each([
    ["DAT246 Empirical software engineering 2024/2025 LP1-LP1", { code: "DAT246", academicYear: 2024, periods: "LP1" }],
    ["TIF083 Experimentell fysik 1 - mätteknik 2024/2025 LP1-LP4", { code: "TIF083", academicYear: 2024, periods: "LP1-LP4" }],
    ["ACEX17 Kandidatarbete 2025/2026 LP3-LP4", { code: "ACEX17", academicYear: 2025, periods: "LP3-LP4" }],
    ["SSY010 Sommarkurs 2023/2024", { code: "SSY010", academicYear: 2023, periods: null }],
  ])("reads %s", (title, expected) => {
    expect(parseTitle(title)).toEqual(expected);
  });

  it("returns null for a survey without a course code", () => {
    expect(parseTitle("Programenkät TKTFY 2024/2025")).toBeNull();
  });
});

describe("parseSurveyRows", () => {
  it("takes the first report link of each row and skips rows without one", () => {
    const html = `<tbody><tr class="srtbl-h1"><td>&nbsp;</td><td class="c0">Svar</td></tr></tbody><tbody><tr class="srtbl-row"><th class="srtbl-rh r0">DAT441 Advanced topics in machine learning 2024/2025 LP1-LP1</th><td class="r0 c0">21 (30,88%)</td><td class="r0 c1"><a href="#" onclick="showReport('27376|-');return false;"><img /></a><a href="#" onclick="showReport('27378|-');return false;"><img /></a></td></tr><tr class="srtbl-row alt"><th class="srtbl-rh r1">MVE095 Options &amp; mathematics 2024/2025 LP2-LP2</th><td class="r1 c0">4 (6,45%)</td><td class="r1 c1"><a href="#" onclick="showReport('27939|-');return false;"><img /></a></td></tr><tr class="srtbl-row"><th class="srtbl-rh r2">TMA000 Utan rapport 2024/2025 LP1-LP1</th><td class="r2 c0">0 (0,00%)</td><td class="r2 c1"></td></tr></tbody>`;

    expect(parseSurveyRows(html)).toEqual([
      { id: 27376, title: "DAT441 Advanced topics in machine learning 2024/2025 LP1-LP1" },
      { id: 27939, title: "MVE095 Options & mathematics 2024/2025 LP2-LP2" },
    ]);
  });
});

/** The option list of one search form field, as the page embeds it in JSON. */
const categoryTree = (itemId: number, options: [number, string][]) =>
  JSON.stringify(
    `<ul>${options.map(([id, label]) => `<li><input id="cbxCat_${id}_S_${itemId}" tag="${id}" type="checkbox" onclick="rcc(${itemId},this);" /><label for="cbxCat_${id}_S_${itemId}">${label}</label></li>`).join("\r\n")}</ul>`,
  );

describe("parseSearchForm", () => {
  it("reads the session key and the programme and year options with their field names", () => {
    const html = `<input type="hidden" name="SessionKey" value="01731f3e-eb8c" /><script type="text/javascript">
buildSelections([{"ID":1,"Max":5,"CategoryTitle":"Program som kurs ingår i","CategoryTree":${categoryTree(1, [[126, "TKTFY - Teknisk fysik, civilingenjör"]])}},{"ID":2,"Max":0,"CategoryTitle":"Läsår","CategoryTree":${categoryTree(
      2,
      [
        [2742, "2024/2025"],
        [2884, "2025/2026"],
      ],
    )}}]);
</script>`;

    expect(parseSearchForm(html)).toEqual({
      sessionKey: "01731f3e-eb8c",
      programmes: { name: "hfCategory1", options: [{ id: 126, label: "TKTFY - Teknisk fysik, civilingenjör" }] },
      years: {
        name: "hfCategory2",
        options: [
          { id: 2742, label: "2024/2025" },
          { id: 2884, label: "2025/2026" },
        ],
      },
    });
  });
});
