/**
 * Parsers for the pages of Chalmers' course survey site. Together with `evaluations.ts`, the only code that knows
 * the site's HTML.
 */
import { PNG } from "pngjs";
import { z } from "zod";
import { ANSWER_SCALE, QUESTIONS, type EvaluationRound, type Question } from "../src/domain/evaluation.ts";

/** Question text in Swedish and English surveys. Teachers' own questions match none of these and are left out. */
const QUESTION_TEXT: Record<Question, RegExp> = {
  overall: /^(Vad är ditt sammanfattande intryck|What is your overall impression)/i,
  teaching: /^(Undervisningen fungerade|The teaching worked)/i,
  structure: /^(Kursens struktur \(|The course structure \()/i,
  literature: /^(Kurslitteraturen|The course literature)/i,
  assessment: /^(Examinationen|The assessment)/i,
  administration: /^(Kursadministrationen|The course administration)/i,
  learningOutcomes: /^(Lärandemålen|The learning outcomes)/i,
  prerequisites: /^(Jag hade tillräckliga förkunskaper|I had enough prior knowledge)/i,
  workload: /^(Kursens arbetsbelastning|The course workload)/i,
};

const DECIMALS = 100;
const ENTITIES: Record<string, string> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " " };

export const decode = (html: string) =>
  html.replace(/&(#x?[\da-f]+|\w+);/gi, (match, entity: string) => {
    if (entity[0] !== "#") return ENTITIES[entity.toLowerCase()] ?? match;
    const hex = entity[1]?.toLowerCase() === "x";
    return String.fromCodePoint(Number.parseInt(entity.slice(hex ? 2 : 1), hex ? 16 : 10));
  });

const textOf = (html: string) =>
  decode(html.replace(/<[^>]*>/g, " "))
    .replace(/\s+/g, " ")
    .trim();

export interface Category {
  id: number;
  label: string;
}

const selectionItemSchema = z.object({ ID: z.number(), CategoryTitle: z.string(), CategoryTree: z.string() });

/** The session key and the programme and academic year options of a report's search form. */
export function parseSearchForm(html: string) {
  const sessionKey = html.match(/name="SessionKey" value="([^"]+)"/)?.[1];
  const selections = html.match(/buildSelections\((\[.*\])\);/)?.[1];
  if (!sessionKey || !selections) throw new Error("Page has no search form");

  const items = z.array(selectionItemSchema).parse(JSON.parse(selections));
  const field = (title: string) => {
    const item = items.find((i) => i.CategoryTitle === title);
    if (!item) throw new Error(`Search form has no "${title}" field`);
    const options = item.CategoryTree.matchAll(/tag="(\d+)"[^>]*\/>\s*<label[^>]*>([^<]*)<\/label>/g);
    return {
      name: `hfCategory${item.ID}`,
      options: [...options].map(([, id, label]): Category => ({ id: Number(id), label: decode(label!).trim() })),
    };
  };
  return { sessionKey, programmes: field("Program som kurs ingår i"), years: field("Läsår") };
}

/** Survey ids and titles in a search result. A row can link several copies of the same survey, so it takes the first. */
export function parseSurveyRows(html: string) {
  return [...html.matchAll(/<th class="srtbl-rh[^"]*">([^<]*)<\/th>(.*?)<\/tr>/g)].flatMap(([, title, cells]) => {
    const id = cells!.match(/showReport\('(\d+)\|-'\)/)?.[1];
    return id ? [{ id: Number(id), title: decode(title!).trim() }] : [];
  });
}

const TITLE = /^([A-Z]{3}[A-Z\d]{3})\b.*?\b(\d{4})\/\d{4}(?:\s+(LP\d)(?:-(LP\d))?)?/;

/**
 * "TIF083 Experimentell fysik 1 2024/2025 LP1-LP4" is course TIF083, academic year 2024, periods "LP1-LP4".
 * Null for surveys that are not about one course round.
 */
export function parseTitle(title: string): (Pick<EvaluationRound, "academicYear" | "periods"> & { code: string }) | null {
  const match = title.match(TITLE);
  if (!match) return null;
  const [, code, year, from, to = from] = match;
  return { code: code!, academicYear: Number(year), periods: from ? (to === from ? from : `${from}-${to}`) : null };
}

/**
 * Answer counts, the link to the meeting minutes, the mean of each standard question, and the address of the
 * overall question's answer chart relative to the report.
 */
export function parseReport(html: string) {
  const header = textOf(html.match(/<h1[^>]*>.*?<\/p>/s)?.[0] ?? "");
  const respondents = header.match(/(?:Antal respondenter|Respondents):\s*(\d+)/)?.[1];
  const answers = header.match(/(?:Antal svar|Answer Count):\s*(\d+)/)?.[1];
  if (respondents === undefined || answers === undefined) throw new Error("Report has no answer counts");

  const minutes = html.match(/data-autogenerated="protocol-link"><a href="([^"]+)"/)?.[1];
  const means: EvaluationRound["means"] = {};
  let overallChart: string | null = null;
  // Each question is a chart followed by a table of its mean and median.
  const chunks = html.split('<table class="srtbl"');
  for (const [index, chunk] of chunks.entries()) {
    const row = chunk.match(/^[^>]*>.*?<th class="srtbl-rh">(.*?)<\/th><td class="srtbl-cell">([\d.,]+)<\/td>/s);
    if (!index || !row) continue;
    const key = QUESTIONS.find((q) => QUESTION_TEXT[q].test(textOf(row[1]!)));
    // Swedish reports write "3,72".
    const mean = Number(row[2]!.replace(",", "."));
    if (!key || key in means || mean < ANSWER_SCALE.min || mean > ANSWER_SCALE.max) continue;
    means[key] = Math.round(mean * DECIMALS) / DECIMALS;
    if (key === "overall")
      overallChart =
        [...chunks[index - 1]!.matchAll(/<img class="srchart"[^>]*src="images\/loading\.gif(\?k=[^"]+)"/g)].at(-1)?.[1] ?? null;
  }
  return { respondents: Number(respondents), answers: Number(answers), minutes: minutes ? decode(minutes) : null, means, overallChart };
}

/** Chart images are this wide. The bar positions below hold at this width. */
export const CHART_WIDTH = 930;
const BAR_COLOR = [46, 139, 87];
/** Bars for answers 1 to 5 are centred on these rows, top to bottom. */
const FIRST_BAR_Y = 86;
const BAR_STEP = 28;
/** Reports round means to two decimals. */
const MEAN_TOLERANCE = 0.006;
/** Bars are whole pixels long and start a little off the axis, so each may be off by this much from a straight line. */
const BAR_TOLERANCE_PX = 1.5;

/**
 * How many answered each option, read from a bar chart of one question. Bar lengths give the shares. The count is the
 * largest one up to `answers` whose bars all fit whole answers and give the reported mean, since some respondents skip
 * a question. Null when no count fits, so a changed chart layout gives no data rather than wrong data.
 */
export function parseAnswerChart(png: Buffer, answers: number, reportedMean: number): number[] | null {
  const { width, height, data } = PNG.sync.read(png);
  const options = ANSWER_SCALE.max - ANSWER_SCALE.min + 1;
  const barEnds = Array.from({ length: options }, () => -1);
  let axis = width;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4;
      if (data[i] !== BAR_COLOR[0] || data[i + 1] !== BAR_COLOR[1] || data[i + 2] !== BAR_COLOR[2]) continue;
      const option = Math.round((y - FIRST_BAR_Y) / BAR_STEP);
      if (option < 0 || option >= options) return null;
      axis = Math.min(axis, x);
      barEnds[option] = Math.max(barEnds[option]!, x);
    }
  }
  const lengths = barEnds.map((end) => (end < 0 ? 0 : end - axis + 1));
  const total = lengths.reduce((sum, length) => sum + length, 0);
  if (!total) return null;

  for (let count = answers; count > 0; count--) {
    const counts = lengths.map((length) => Math.round((length / total) * count));
    const mean = counts.reduce((sum, n, i) => sum + (ANSWER_SCALE.min + i) * n, 0) / count;
    const sums = counts.reduce((sum, n) => sum + n, 0) === count;
    if (sums && Math.abs(mean - reportedMean) < MEAN_TOLERANCE && barsFit(lengths, counts)) return counts;
  }
  return null;
}

/** Whether bar lengths lie on a line `length = count * pxPerAnswer + offset`, with empty bars for zero counts. */
function barsFit(lengths: readonly number[], counts: readonly number[]): boolean {
  if (lengths.some((length, i) => length > 0 !== counts[i]! > 0)) return false;
  const bars = lengths.flatMap((length, i) => (length ? [{ count: counts[i]!, length }] : []));
  const n = bars.length;
  const [sc, sl, scc, scl] = bars.reduce(
    ([c, l, cc, cl], bar) => [c + bar.count, l + bar.length, cc + bar.count ** 2, cl + bar.count * bar.length],
    [0, 0, 0, 0],
  );
  const denominator = n * scc - sc ** 2;
  // One bar, or bars with equal counts, fit any line.
  if (!denominator) return true;
  const slope = (n * scl - sc * sl) / denominator;
  const offset = (sl - slope * sc) / n;
  return bars.every(({ count, length }) => Math.abs(length - (count * slope + offset)) <= BAR_TOLERANCE_PX);
}
